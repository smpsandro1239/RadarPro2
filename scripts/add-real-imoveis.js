async function main() {
  let added = 0;
  let skipped = 0;

  for (const p of props) {
    try {
      await c.execute({
        sql: `INSERT OR IGNORE INTO properties (id, source, source_name, url, title, district, municipality, type, price, market_value, discount_pct, score, rentability, images, is_active, check_status, created_at, updated_at)
              VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 'pending', ?, ?)`,
        args: [
          p.id,
          p.source,
          p.sourceName,
          p.url,
          p.title,
          p.district,
          p.municipality,
          p.type,
          p.price,
          p.marketValue,
          p.discountPct,
          p.score,
          p.rentability,
          JSON.stringify([p.images]),
          Math.floor(Date.now() / 1000),
          Math.floor(Date.now() / 1000),
        ],
      });
      added++;
    } catch (e) {
      skipped++;
    }
  }

  const total = await c.execute("SELECT COUNT(*) as count FROM properties");
  console.log(`\n✅ Total properties in database: ${total.rows[0][0]}`);
  console.log(`✅ Added: ${added}, Skipped (duplicates): ${skipped}`);

  // Verify by district
  const byDistrict = await c.execute(
    "SELECT district, COUNT(*) as count FROM properties GROUP BY district ORDER BY count DESC"
  );
  console.log("\n📊 Por distrito:");
  for (const row of byDistrict.rows) {
    console.log(`   ${row[0]}: ${row[1]}`);
  }

  // Count with images
  const withImages = await c.execute(
    "SELECT COUNT(*) as count FROM properties WHERE images IS NOT NULL AND images != '[]' AND images != ''"
  );
  console.log(`\n🖼️ Com imagens reais: ${withImages.rows[0][0]}`);
  console.log(`📭 Sem imagens: ${total.rows[0][0] - withImages.rows[0][0]}`);
}

